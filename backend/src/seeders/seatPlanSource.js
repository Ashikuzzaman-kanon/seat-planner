/**
 * Seat plans transcribed from published Bangladesh Railway coach diagrams.
 *
 * Rows are written in a compact notation so the transcription stays close to
 * the source diagram and is easy to proof-read against it:
 *
 *   "12 11 | 10 9 8"     two seats, the corridor, three seats
 *   "_"                  a blank cell (table, toilet, vestibule, gap)
 *   "91w 90 89c"         explicit window / corridor markers
 *
 * Seat flags, appended to the number:
 *   w  window seat (full window)
 *   h  half window
 *   c  explicitly not a window (corridor or middle seat)
 *   p  charging port
 *   f  fan
 *
 * Where the diagram does not state window positions, a seat is treated as a
 * window seat when it sits at either outer edge of its row — which is how every
 * one of these layouts is actually built. Diagrams that *do* state it (the W/C
 * columns, the w/c prefixes) are marked explicitly and override that rule.
 *
 * `seats` is the seat count printed on the diagram. The importer refuses to
 * insert a plan whose transcription does not produce exactly that many seats,
 * which is what catches a mis-read digit.
 */

